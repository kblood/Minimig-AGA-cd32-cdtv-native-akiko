module tb_sprite_mux_load;

parameter integer FRAMES  = 16;
parameter integer STAGGER = 0;   // per-sprite VSTART stagger in lines

integer tb_errs = 1;

initial begin
	#1400000000 $fatal(1, "tb_sprite_mux_load: watchdog timeout");
end

logic clk = 0;
initial forever #17.6 clk = ~clk;      // ~28.375 MHz

logic reset_n = 1'b0;
logic reset   = 1'b1;
logic run     = 1'b0;

wire clk7_en, clk7n_en, c1, c3, cck;

amiga_clk u_clk (
	.clk_28 (clk), .clk7_en (clk7_en), .clk7n_en (clk7n_en),
	.c1 (c1), .c3 (c3), .cck (cck), .eclk (), .reset_n (reset_n)
);

wire [8:0]  hpos;
wire [10:0] vpos;
wire        vbl, vblend, eol, eof;

agnus_beamcounter u_bc (
	.clk (clk), .clk7_en (clk7_en), .reset (reset), .cck (cck),
	.ntsc (1'b0), .aga (1'b0), .ecs (1'b0), .a1k (1'b0),
	.data_in (16'h0000), .data_out (), .reg_address_in (8'hFF),
	.hpos (hpos), .vpos (vpos),
	._hsync (), ._vsync (), .field1 (), .lace (), ._csync (),
	.hblank (), .vblank (), .vbl (vbl), .vblend (vblend),
	.eol (eol), .eof (eof), .vbl_int (),
	.htotal_out (), .harddis_out (), .varbeamen_out ()
);

// ------------------------------------------------------------- the four arms
wire [31:0] e1, e3, e6, e8;
wire [31:0] s1, s3, s6, s8;
wire [31:0] p1, p3, p6, p8;
wire [31:0] d1, d3, d6, d8;

spr_env #(.NACT(1), .STAG(STAGGER)) env1 (.clk(clk), .clk7_en(clk7_en), .reset(reset), .hpos(hpos),
	.vpos(vpos), .vbl(vbl), .vblend(vblend), .run(run),
	.errs(e1), .slots_checked(s1), .fetches_pos(p1), .fetches_dat(d1));
spr_env #(.NACT(3), .STAG(STAGGER)) env3 (.clk(clk), .clk7_en(clk7_en), .reset(reset), .hpos(hpos),
	.vpos(vpos), .vbl(vbl), .vblend(vblend), .run(run),
	.errs(e3), .slots_checked(s3), .fetches_pos(p3), .fetches_dat(d3));
spr_env #(.NACT(6), .STAG(STAGGER)) env6 (.clk(clk), .clk7_en(clk7_en), .reset(reset), .hpos(hpos),
	.vpos(vpos), .vbl(vbl), .vblend(vblend), .run(run),
	.errs(e6), .slots_checked(s6), .fetches_pos(p6), .fetches_dat(d6));
spr_env #(.NACT(8), .STAG(STAGGER)) env8 (.clk(clk), .clk7_en(clk7_en), .reset(reset), .hpos(hpos),
	.vpos(vpos), .vbl(vbl), .vblend(vblend), .run(run),
	.errs(e8), .slots_checked(s8), .fetches_pos(p8), .fetches_dat(d8));

// ===========================================================================
// DIRECT MULTIPLEX INSTRUMENTS (env6; sprsel is env-independent anyway)
// ===========================================================================
wire [2:0] sprsel  = env6.u_spr.sprsel;
wire [2:0] dsprite = env6.u_spr.sprite;
wire       win     = (hpos[2:1] == 2'b01);

reg  [7:0] scan_mask = 8'h00;
reg        win_d     = 1'b0;
reg  [2:0] sprsel_d  = 3'd0;

integer win_n = 0, win_incomplete = 0, win_dup = 0;
integer match_n = 0, match_min = 1000, match_max = 0;
integer scan_stall = 0;
integer last_latch_t = 0, margin_min = 1000000, margin_max = 0, margin_n = 0;
integer clk_t = 0;

always @(posedge clk) clk_t    <= clk_t + 1;
always @(posedge clk) sprsel_d <= sprsel;

always @(posedge clk) if (run && !reset) begin
	if (sprsel === sprsel_d) scan_stall <= scan_stall + 1;

	if (win) begin
		if (!win_d) begin
			scan_mask <= (8'h01 << sprsel);
			match_n   <= (dsprite === sprsel) ? 1 : 0;
		end else begin
			if (scan_mask[sprsel]) win_dup <= win_dup + 1;
			scan_mask <= scan_mask | (8'h01 << sprsel);
			if (dsprite === sprsel) match_n <= match_n + 1;
		end
		if (dsprite === sprsel) last_latch_t <= clk_t;
	end else if (win_d) begin
		win_n <= win_n + 1;
		if (scan_mask !== 8'hFF) win_incomplete <= win_incomplete + 1;
		if (match_n < match_min) match_min <= match_n;
		if (match_n > match_max) match_max <= match_n;
	end
	win_d <= win;

	// first use of the latched value = the sprite's POS/DATA slot
	if (clk7_en && env6.tb_enable && hpos[1:0]==2'b01 && hpos[2]) begin
		margin_n <= margin_n + 1;
		if ((clk_t - last_latch_t) < margin_min) margin_min <= clk_t - last_latch_t;
		if ((clk_t - last_latch_t) > margin_max) margin_max <= clk_t - last_latch_t;
	end
end

// ------------------------------------------- scan phase at bus-write time
// Every sprpos/sprctl bank write happens on a clk7_en edge. Which scan slot is
// the shared comparator reading at that instant? If a write can coincide with
// sprsel == the sprite being written, the comparator sees pre-write data for
// one CCK (distributed-RAM read-during-write). This measures how often that
// happens and on which slots.
integer wr_phase [0:7];
integer wr_same  = 0;
integer wr_tot   = 0;
integer j;
initial for (j = 0; j < 8; j = j + 1) wr_phase[j] = 0;

wire spr_wr = env6.clk7_en && (env6.reg_address_in[8:6] == 3'b101) &&
              (env6.reg_address_in[2] == 1'b0);
wire [2:0] spr_wr_sel = env6.ackdma ? env6.tb_sprite : env6.reg_address_in[5:3];

always @(posedge clk) if (run && !reset && spr_wr) begin
	wr_tot         <= wr_tot + 1;
	wr_phase[sprsel] <= wr_phase[sprsel] + 1;
	if (sprsel === spr_wr_sel) wr_same <= wr_same + 1;
end

// ------------------------------------------------------------ liveness guard
integer lines_seen = 0, frames_seen = 0;
reg [10:0] vpos_q = 11'd0;
always @(posedge clk) begin
	vpos_q <= vpos;
	if (!reset && vpos !== vpos_q) lines_seen <= lines_seen + 1;
end
always @(posedge clk) if (clk7_en && eof) frames_seen <= frames_seen + 1;

// ===========================================================================
integer f, k;
integer base_i;

task seed_all;
	begin
