//
// agnus_spritedma sprite-select MULTIPLEX bench, under realistic multi-sprite load.
//
// QUESTION UNDER TEST
// -------------------
// The 8 sprites' vertical comparators in rtl/agnus_spritedma.v are not eight
// parallel instances. They are ONE shared comparator time-multiplexed by a
// free-running 28 MHz scan counter:
//
//   always @ (posedge clk) if (sprsel[2]==hpos[0]) sprsel <= sprsel + 1'b1;   // :138
//   assign vstart[7:0] = sprpos[sprsel];                                      // :213
//   assign {vstop[7:0],...} = sprctl[sprsel];                                 // :225
//   always @ (posedge clk) dmastate_mem[sprsel] <= dmastate_in;               // :234
//   assign dmastate = dmastate_mem[sprsel];                                   // :238
//   always @ (posedge clk) if (sprite==sprsel && hpos[2:1]==2'b01)
//     sprdmastate <= dmastate & ~(...);                                       // :250
//   always @ (posedge clk) if (sprite==sprsel && hpos[2:1]==2'b01)
//     sprvstop <= (vstop==vpos);                                              // :255
//
// This is the one structural piece of the sprite DMA design with no real-Agnus
// analogue. If the scan cannot serve all 8 slots inside the window where the
// per-sprite results have to be ready, a sprite's DMA decision would be made
// from STALE data or from a NEIGHBOUR's comparison, and the margin would shrink
// as more sprites go live. That is the "fine with a few sprites, breaks with
// many" signature of the Hybris reward-screen jitter.
//
// METHOD
// ------
// Real amiga_clk + real agnus_beamcounter (sim shim) + real, unmodified
// agnus_spritedma. Four independent DUT environments run concurrently off one
// beamcounter, with 1 / 3 / 6 / 8 simultaneously active sprites, so error rate
// and margin can be compared directly across sprite count.
//
// Each environment is a closed sprite-DMA loop, not a stub: a chip-RAM model
// holds real sprite lists, ackdma is granted on every request, the fetched word
// is fed back on data_in with reg_address_in = reg_address_out (exactly what
// agnus.v does on ack_spr), so SPRxPOS/SPRxCTL are loaded BY DMA and the
// pointer walks the list. A copper-style SPRxPT reload runs each vblank.
//
// STIMULUS = MEASURED HYBRIS REWARD-SCREEN DATA
// ---------------------------------------------
// From research/tmp/hybris_r17/spr3.txt + spr4.txt (WinUAE cycle-exact sprite
// DMA trace of the reward screen, frames 6410-7412), decoded:
//   - sprites 0..5 active, 6 and 7 parked on a terminator entry
//   - each active sprite's 1 KB block holds EIGHT list entries, 36 bytes apart
//     = 2 control words + 8 scanlines x 2 data words
//   - all six sprites share IDENTICAL VSTART/VSTOP; they differ only in HSTART
//   - entry i: VSTART = base + 22*i, VSTOP = VSTART + 8
//   - the table scrolls, so `base` walks (f6411 base=99, f6450 base=85,
//     f7331 base=217). This bench walks base every frame to sweep every phase
//     of the vertical compare against the beam.
//
// PASS = every sprite DMA slot in every line of every frame matches an ideal
// 8-PARALLEL-comparator reference model, for all four sprite counts.
//
// The reference is deliberately NOT a copy of the mux: it keeps 8 independent
// vstart/vstop/dmastate sets and latches each sprite's result on its own enable,
// which is what the hardware the RTL is emulating would do.
//
// NEGATIVE CONTROL: run_sprite_mux_mutant.do compiles mutants generated by
// patch_sprmux_mutant.py (latch window off by one sprite slot, adjacent-slot
// aliasing, broken scan lock, scan running 4x too slow) and this same bench
// must FAIL on each of them.

`timescale 1ns / 1ps

// ===========================================================================
// One DUT + chip RAM + reference model, parameterised by active sprite count.
// ===========================================================================
module spr_env #(
	parameter integer NACT = 6,     // simultaneously active sprites
	parameter integer STAG = 0      // per-sprite VSTART stagger, in scanlines
) (
	input               clk,
	input               clk7_en,
	input               reset,
	input        [8:0]  hpos,
	input        [10:0] vpos,
	input               vbl,
	input               vblend,
	input               run,
	output       [31:0] errs,
	output       [31:0] slots_checked,
	output       [31:0] fetches_pos,
	output       [31:0] fetches_dat
);

localparam [20:1] SPRBASE_W = 20'h08000;    // $010000 >> 1
localparam integer BLKW     = 'h200;        // $400 bytes = 512 words
localparam integer ENTW     = 18;           // 36 bytes  = 18 words

// ------------------------------------------------------------------ chip RAM
reg [15:0] cram [0:8*BLKW-1];

// -------------------------------------------------------------------- the DUT
wire        reqdma;
wire [8:1]  reg_address_out;
wire [20:1] address_out;

reg  [8:1]  reg_address_in;
reg  [15:0] data_in;

reg         spren = 1'b0;
wire        ackdma = reqdma & spren;

agnus_spritedma u_spr (
	.clk             (clk),
	.clk7_en         (clk7_en),
	.reset           (reset),
	.aga             (1'b0),          // Hybris is OCS
	.ecs             (1'b0),
	.reqdma          (reqdma),
	.ackdma          (ackdma),
	.hpos            (hpos),
	.vpos            (vpos),
	.vbl             (vbl),
	.vblend          (vblend),
	.reg_address_in  (reg_address_in),
	.reg_address_out (reg_address_out),
	.data_in         (data_in),
	.address_out     (address_out)
);

// ------------------------------------------- bus: DMA loopback + copper writes
// agnus.v drives reg_address = reg_address_spr and ack_spr = 1 on a granted
// sprite slot, and the chip RAM word arrives on data_in in the same bus cycle.
reg  [8:1]  cop_addr = 8'hFF;
reg  [15:0] cop_data = 16'h0000;

wire [31:0] cram_idx = {12'd0, address_out} - {12'd0, SPRBASE_W};
wire [15:0] cram_q   = (cram_idx < 8*BLKW) ? cram[cram_idx[12:0]] : 16'h0000;

always @(*) begin
	if (ackdma) begin
		reg_address_in = reg_address_out;
		data_in        = cram_q;
	end else begin
		reg_address_in = cop_addr;
		data_in        = cop_data;
	end
end

// ===========================================================================
// REFERENCE MODEL -- eight independent comparators, no shared scan.
// ===========================================================================
reg  [9:0]  ref_vstart [0:7];
reg  [9:0]  ref_vstop  [0:7];
reg         ref_dma    [0:7];   // continuously evaluated per-sprite dma state
reg         ref_sprdma [0:7];   // per-sprite latched copy
reg         ref_svstop [0:7];
reg  [20:1] ref_ptr    [0:7];

// tb-side copy of the slot's sprite number, computed from hpos alone.
reg  [2:0]  tb_sprite = 3'd0;
always @(posedge clk) if (clk7_en && hpos[2:0]==3'b001)
	tb_sprite <= {hpos[5]^hpos[4], ~hpos[4], hpos[3]};

// tb-side copy of the sprite DMA window.
reg tb_enable = 1'b0;
always @(posedge clk) if (clk7_en) begin
	if      (hpos[8:1]==8'h18 && hpos[0]) tb_enable <= 1'b1;
	else if (hpos[8:1]==8'h38 && hpos[0]) tb_enable <= 1'b0;
end

// Register decode, independent of the DUT's internal ptsel/pcsel.
wire        w_ptr    = (reg_address_in[8:5]==4'h9);       // $120-$13E
wire        w_posctl = (reg_address_in[8:6]==3'b101);     // $140-$17E
wire [2:0]  w_pt_sel = reg_address_in[4:2];
wire [2:0]  w_pc_sel = ackdma ? tb_sprite : reg_address_in[5:3];
wire [20:1] ref_newptr = ref_ptr[tb_sprite] + 20'd1;      // fmode = 0

integer i;
always @(posedge clk) begin
	if (clk7_en) begin
		if (ackdma)
			ref_ptr[tb_sprite] <= ref_newptr;
		else if (w_ptr && !reg_address_in[1])
			ref_ptr[w_pt_sel][20:16] <= data_in[4:0];
		else if (w_ptr &&  reg_address_in[1])
			ref_ptr[w_pt_sel][15:1]  <= data_in[15:1];

		if (w_posctl && reg_address_in[2:1]==2'b00)
			ref_vstart[w_pc_sel][7:0] <= data_in[15:8];
		if (w_posctl && reg_address_in[2:1]==2'b01) begin
			ref_vstop [w_pc_sel][7:0] <= data_in[15:8];
			ref_vstart[w_pc_sel][9]   <= data_in[6];
			ref_vstop [w_pc_sel][9]   <= data_in[5];
			ref_vstart[w_pc_sel][8]   <= data_in[2];
			ref_vstop [w_pc_sel][8]   <= data_in[1];
		end
	end
end

// Continuous per-sprite DMA state -- 8 parallel copies of the RTL's rule.
// ecs = 0, so vstart[9]/vstop[9] are masked out of the compare.
always @(posedge clk) begin
	for (i = 0; i < 8; i = i + 1) begin
		if (vbl || ({1'b0, ref_vstop[i][8:0]} == vpos[9:0]))
			ref_dma[i] <= 1'b0;
		else if ({1'b0, ref_vstart[i][8:0]} == vpos[9:0])
			ref_dma[i] <= 1'b1;
	end
end

// Per-sprite latch, each on its OWN enable. No shared scan slot.
always @(posedge clk) begin
	if (hpos[2:1]==2'b01) begin
		ref_sprdma[tb_sprite] <= ref_dma[tb_sprite];
		ref_svstop[tb_sprite] <= ({1'b0, ref_vstop[tb_sprite][8:0]} == vpos[9:0]);
	end
end

// ===========================================================================
// CHECKER -- every sprite DMA slot of every line.
// ===========================================================================
integer e_cnt = 0, s_cnt = 0, f_pos = 0, f_dat = 0, rpt = 0;
assign errs          = e_cnt;
assign slots_checked = s_cnt;
assign fetches_pos   = f_pos;
assign fetches_dat   = f_dat;

wire slot_now = clk7_en && tb_enable && (hpos[1:0]==2'b01);

reg        exp_req;
reg [8:1]  exp_addr;

always @(*) begin
	if (vblend || (ref_svstop[tb_sprite] && ~vbl)) begin
		exp_req  = 1'b1;
		exp_addr = hpos[2] ? {3'b101, tb_sprite, 2'b00} : {3'b101, tb_sprite, 2'b01};
	end else if (ref_sprdma[tb_sprite]) begin
		exp_req  = 1'b1;
		exp_addr = hpos[2] ? {3'b101, tb_sprite, 2'b10} : {3'b101, tb_sprite, 2'b11};
	end else begin
		exp_req  = 1'b0;
		exp_addr = 8'hFF;
	end
end

always @(posedge clk) if (run && !reset) begin
	if (u_spr.sprite !== tb_sprite) begin
		e_cnt <= e_cnt + 1;
		if (rpt < 10) begin
			$display("  [N=%0d] SPRITE-IDX vpos=%0d hpos=%0h dut=%0d tb=%0d",
			         NACT, vpos, hpos, u_spr.sprite, tb_sprite);
			rpt <= rpt + 1;
		end
	end else if (u_spr.enable !== tb_enable) begin
		e_cnt <= e_cnt + 1;
		if (rpt < 10) begin
			$display("  [N=%0d] ENABLE     vpos=%0d hpos=%0h dut=%0d tb=%0d",
			         NACT, vpos, hpos, u_spr.enable, tb_enable);
			rpt <= rpt + 1;
		end
	end else if (slot_now) begin
		s_cnt <= s_cnt + 1;
		if (exp_req) begin
			if (exp_addr[2] == 1'b0) f_pos <= f_pos + 1;
			else                     f_dat <= f_dat + 1;
		end
		if (reqdma !== exp_req) begin
			e_cnt <= e_cnt + 1;
			if (rpt < 10) begin
				$display("  [N=%0d] REQDMA   vpos=%0d hpos=%0h spr%0d dut=%0b ref=%0b  (sprdma d=%0b r=%0b, svstop d=%0b r=%0b)",
				         NACT, vpos, hpos, tb_sprite, reqdma, exp_req,
				         u_spr.sprdmastate, ref_sprdma[tb_sprite],
				         u_spr.sprvstop,    ref_svstop[tb_sprite]);
				rpt <= rpt + 1;
			end
		end else if (exp_req && (reg_address_out !== exp_addr)) begin
			e_cnt <= e_cnt + 1;
			if (rpt < 10) begin
				$display("  [N=%0d] REGADDR  vpos=%0d hpos=%0h spr%0d dut=%0h ref=%0h",
				         NACT, vpos, hpos, tb_sprite, reg_address_out, exp_addr);
				rpt <= rpt + 1;
			end
		end else if (exp_req && (address_out !== ref_ptr[tb_sprite])) begin
			e_cnt <= e_cnt + 1;
			if (rpt < 10) begin
				$display("  [N=%0d] POINTER  vpos=%0d hpos=%0h spr%0d dut=%05h ref=%05h",
				         NACT, vpos, hpos, tb_sprite, address_out, ref_ptr[tb_sprite]);
				rpt <= rpt + 1;
			end
		end else if (u_spr.sprdmastate !== ref_sprdma[tb_sprite]) begin
			e_cnt <= e_cnt + 1;
			if (rpt < 10) begin
				$display("  [N=%0d] SPRDMA   vpos=%0d hpos=%0h spr%0d dut=%0b ref=%0b",
				         NACT, vpos, hpos, tb_sprite, u_spr.sprdmastate, ref_sprdma[tb_sprite]);
				rpt <= rpt + 1;
			end
		end else if (u_spr.sprvstop !== ref_svstop[tb_sprite]) begin
			e_cnt <= e_cnt + 1;
			if (rpt < 10) begin
				$display("  [N=%0d] SPRVSTOP vpos=%0d hpos=%0h spr%0d dut=%0b ref=%0b",
				         NACT, vpos, hpos, tb_sprite, u_spr.sprvstop, ref_svstop[tb_sprite]);
				rpt <= rpt + 1;
			end
		end
	end
end

// ===========================================================================
// Sprite list authoring + the copper's per-frame SPRxPT reload.
// ===========================================================================
function [15:0] mk_pos (input [9:0] vs_, input [8:0] hs_);
	mk_pos = {vs_[7:0], hs_[8:1]};
endfunction

function [15:0] mk_ctl (input [9:0] vs_, input [9:0] ve_, input [8:0] hs_);
	mk_ctl = {ve_[7:0], 1'b0, vs_[9], ve_[9], 2'b00, vs_[8], ve_[8], hs_[0]};
endfunction

integer s, en, w;
reg [9:0] vs, ve;
reg [8:0] hs;

task build_lists (input [8:0] base);
	begin
		for (s = 0; s < 8; s = s + 1) begin
			hs = 9'h040 + s*9'h018;
			for (en = 0; en < 8; en = en + 1) begin
				if (s < NACT) begin
					vs = base + en*22 + s*STAG;
					ve = vs + 8;
					cram[s*BLKW + en*ENTW + 0] = mk_pos(vs, hs);
					cram[s*BLKW + en*ENTW + 1] = mk_ctl(vs, ve, hs);
				end else begin
					// parked sprite: terminator, exactly as Hybris leaves
					// sprites 6 and 7 on the reward screen.
					cram[s*BLKW + en*ENTW + 0] = 16'h0000;
					cram[s*BLKW + en*ENTW + 1] = 16'h0000;
				end
				for (w = 2; w < ENTW; w = w + 1)
					cram[s*BLKW + en*ENTW + w] = 16'hA500 + s*16 + en;
			end
			for (w = 8*ENTW; w < BLKW; w = w + 1)
				cram[s*BLKW + w] = 16'h0000;    // list terminator + tail
		end
	end
endtask

// Copper-style pointer reload during vblank: 16 consecutive register writes
// starting at hpos $80 on line 20 of every frame -- clear of the sprite DMA
// window ($31..$71) and clear of the vblend refetch line ($19).
//   SPRnPTH = $120+4n -> reg_address_in = {4'h9, n, 1'b0}, data[4:0]  = $01
//   SPRnPTL = $122+4n -> reg_address_in = {4'h9, n, 1'b1}, data[15:1] = n*$200
reg [4:0] cop_i = 5'd16;
always @(posedge clk) if (clk7_en) begin
	if (vpos == 11'd20 && hpos == 9'h080) cop_i <= 5'd0;
	else if (cop_i < 5'd16)               cop_i <= cop_i + 5'd1;

	if (cop_i < 5'd16) begin
		cop_addr <= {4'h9, cop_i[3:1], cop_i[0]};
		cop_data <= cop_i[0] ? {3'd0, cop_i[3:1], 10'd0} : 16'h0001;
	end else begin
		cop_addr <= 8'hFF;
		cop_data <= 16'h0000;
	end
end

initial begin
	for (i = 0; i < 8; i = i + 1) begin
		ref_vstart[i] = 10'd0; ref_vstop[i] = 10'd0;
		ref_dma[i] = 1'b0; ref_sprdma[i] = 1'b0; ref_svstop[i] = 1'b0;
		ref_ptr[i] = 20'd0;
	end
end

endmodule


