task build_all (input [8:0] base);
	begin
		env1.build_lists(base); env3.build_lists(base);
		env6.build_lists(base); env8.build_lists(base);
	end
endtask

task wait_vpos (input [10:0] target);
	begin
		while (vpos !== target) @(posedge clk);
		while (vpos === target) @(posedge clk);
	end
endtask

initial begin
	reset = 1'b1; reset_n = 1'b0;
	repeat (40) @(posedge clk);
	reset_n = 1'b1;
	repeat (40) @(posedge clk);
	reset = 1'b0;

	// agnus_beamcounter's hpos/vpos and agnus_spritedma's sprsel/sprite have no
	// reset term. On the FPGA Quartus powers them up at 0; in simulation they
	// start X and never recover. Seed them exactly as the device comes up.
	// Sim hygiene, not a behavioural change.
	u_bc.hpos[8:1] = 8'd0;
	u_bc.vpos      = 11'd0;
	seed_all;
	repeat (8) @(posedge clk);

	build_all(9'd105);
	env1.spren = 1'b1; env3.spren = 1'b1; env6.spren = 1'b1; env8.spren = 1'b1;

	// one settling frame (pointer reload + first vblend refetch), then arm.
	wait_vpos(11'd300);
	wait_vpos(11'd30);
	run = 1'b1;

	for (f = 0; f < FRAMES; f = f + 1) begin
		wait_vpos(11'd5);                     // deep inside vblank
		base_i = 105 - f*7;
		if (base_i < 0) base_i = base_i + 260;
		build_all(base_i[8:0]);
		wait_vpos(11'd300);
	end

	report;
	$finish;
end

